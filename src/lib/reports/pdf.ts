import "server-only";
import { jsPDF } from "jspdf";
import { autoTable } from "jspdf-autotable";
import type { Sheet } from "./export";

const CRIMSON: [number, number, number] = [190, 18, 60];
const INK: [number, number, number] = [15, 23, 42];

function logo(doc: jsPDF, x: number, y: number, size: number) {
  doc.setFillColor(...CRIMSON);
  doc.roundedRect(x, y, size, size, size / 4, size / 4, "F");
  doc.setTextColor(255, 255, 255).setFont("helvetica", "bold").setFontSize(size * 1.6);
  doc.text("C", x + size / 2, y + size * 0.72, { align: "center" });
  doc.setFontSize(size * 1.9).setTextColor(...INK).text("Call", x + size + 4, y + size * 0.78);
  doc.setTextColor(...CRIMSON).text("Opps", x + size + 4 + doc.getTextWidth("Call"), y + size * 0.78);
}

/** The "Analytics Hub Report": cover with applied filters, then one table per sheet, footer on every page. */
export function toPdf(meta: { subtitle: string; generated: string; filters: [string, string][] }, sheets: Sheet[]): Buffer {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  doc.setDrawColor(...CRIMSON).setLineWidth(1.2).line(0, 1, W, 1);
  logo(doc, W / 2 - 22, 30, 9);
  doc.setTextColor(...INK).setFont("helvetica", "bold").setFontSize(20).text("Analytics Hub Report", W / 2, 62, { align: "center" });
  doc.setFont("helvetica", "normal").setFontSize(10).setTextColor(100, 116, 139);
  doc.text(meta.subtitle, W / 2, 69, { align: "center" });
  doc.text(`Generated ${meta.generated} · Asia/Kolkata (IST)`, W / 2, 74, { align: "center" });
  doc.setTextColor(...CRIMSON).setFont("helvetica", "bold").setFontSize(12).text("Applied filters", 14, 90);
  autoTable(doc, {
    startY: 93, head: [["Filter", "Selection"]], body: meta.filters, theme: "plain",
    headStyles: { fillColor: INK, textColor: 255, fontStyle: "bold" }, styles: { fontSize: 9, cellPadding: 1.8 },
    columnStyles: { 0: { cellWidth: 45, textColor: [71, 85, 105] } },
  });
  // Tables flow one after another (two or three per page), starting on page 2.
  doc.addPage();
  let y = 22;
  const H0 = doc.internal.pageSize.getHeight();
  for (const s of sheets) {
    if (y > H0 - 50) { doc.addPage(); y = 22; }
    doc.setTextColor(...CRIMSON).setFont("helvetica", "bold").setFontSize(12).text(s.name === "Summary" ? "Key metrics" : s.breakdown ? `Breakdown by ${s.name}` : s.name, 14, y);
    const firstNum = s.columns.findIndex((c) => ["Leads", "Value", "Actual", "Calls"].includes(c));
    autoTable(doc, {
      startY: y + 4, head: [s.columns], body: s.rows.map((r) => r.map(String)), theme: "striped",
      headStyles: { fillColor: INK, textColor: 255, fontSize: 8.5 }, styles: { fontSize: 8, cellPadding: 1.6, overflow: "linebreak" },
      alternateRowStyles: { fillColor: [248, 250, 252] },
      didParseCell: (d) => {
        if (firstNum > 0 && d.column.index >= firstNum) d.cell.styles.halign = "right";
        if (d.section === "body" && d.row.index === s.rows.length - 1 && String(d.row.raw[0 as never]) === "Total") d.cell.styles.fontStyle = "bold";
      },
      margin: { top: 18, bottom: 18 },
    });
    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 12;
  }
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    const H = doc.internal.pageSize.getHeight();
    doc.setFont("helvetica", "normal").setFontSize(8).setTextColor(148, 163, 184);
    doc.text("Generated by CallOpps — Analytics Hub", 14, H - 8);
    doc.text(`Page ${i} of ${pages}`, W - 14, H - 8, { align: "right" });
  }
  return Buffer.from(doc.output("arraybuffer"));
}
